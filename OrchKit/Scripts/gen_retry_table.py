#!/usr/bin/env python3
"""Generates Sources/OrchProtocol/PhoneRetryTableGenerated.swift from the vendored R2 framing vectors.

    gen_retry_table.py [--check]

Source: Tests/OrchTestVectors/r2/r2_framing.json, `tables.retry` (code -> A | B | C-auto | C-review | D) and `tables.retry_context`
(the two codes whose class depends on a fact the answer does not carry). The data is authoritative (orch-52 ruling).
No network and no orch-core checkout are needed: the input is the vendored file. --check regenerates in memory and exits 1 when the
checked-in file differs; CI runs it.

The phone's documented overlay, codes the data does not name that the phone still treats as a delivery fact or an outcome state:
    no_answer, silence            A  (no answer arrived; the same bytes are sent again)
    already_done.unknown          B  (an `already_done` whose status is unknown)
    outcome.pending               B  (the `outcome.get` state `pending` as a code)
A bare `timeout` is NOT in the table (it is D, an unknown code); `relay.timeout` is A because the data says so.
Everything else the data does not name is D (an unknown code is D, 14.4).
"""
import argparse, json, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
VECTORS = HERE.parent / "Tests" / "OrchTestVectors" / "r2" / "r2_framing.json"
OUT = HERE.parent / "Sources" / "OrchProtocol" / "PhoneRetryTableGenerated.swift"

OVERLAY = {"no_answer": "A", "silence": "A", "already_done.unknown": "B", "outcome.pending": "B"}
# codes whose class PhoneRetryTable.classify decides from a context (retry_context); they stay out of the five sets
CONTEXTUAL = {"internal": ("D", {"effects_possible": "B"}), "outcome.unknown_idem": ("C-review", {"before_bound": "B"})}
CLASSES = [("A", "classA"), ("B", "classB"), ("C-auto", "classCAuto"), ("C-review", "classCReview"), ("D", "classD")]


def render(doc: dict) -> str:
    retry = dict(doc["tables"]["retry"])
    ctx = doc["tables"]["retry_context"]
    for code, (base, extra) in CONTEXTUAL.items():
        if retry.get(code) != base or ctx.get(code) != extra:
            raise SystemExit(f"{code}: the data changed ({retry.get(code)!r}, {ctx.get(code)!r}); classify() must be revisited")
    if set(ctx) != set(CONTEXTUAL):
        raise SystemExit(f"retry_context names {sorted(ctx)}: classify() must be revisited")
    for code, cls in OVERLAY.items():
        if code in retry:
            raise SystemExit(f"overlay code {code} is now in the data: drop it from the overlay")
        retry[code] = cls
    if "timeout" in retry:
        raise SystemExit("a bare `timeout` is in the data: orch-52 Q4 must be revisited")
    unknown = set(retry.values()) - {c for c, _ in CLASSES}
    if unknown:
        raise SystemExit(f"unknown classes {sorted(unknown)}")
    out = ["// GENERATED by Scripts/gen_retry_table.py. Do not edit.",
           "// Source: Tests/OrchTestVectors/r2/r2_framing.json tables.retry and tables.retry_context, plus the overlay documented in the generator.",
           "", "enum PhoneRetryTableGenerated {"]
    for cls, name in CLASSES:
        codes = sorted(c for c, k in retry.items() if k == cls and c not in CONTEXTUAL)
        body = ",\n".join(f'        "{c}"' for c in codes)
        out.append(f"    static let {name}: Set<String> = [\n{body},\n    ]")
    out.append("    /// Codes whose class `PhoneRetryTable.classify` decides from a context: `internal` (D; B once effects are possible) and")
    out.append("    /// `outcome.unknown_idem` (C-review after its bound; B before it).")
    out.append('    static let contextual: Set<String> = ["internal", "outcome.unknown_idem"]')
    out.append("    /// The overlay (not in the data): see the generator.")
    out.append('    static let overlay: Set<String> = [' + ", ".join(f'"{c}"' for c in sorted(OVERLAY)) + "]")
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(json.loads(VECTORS.read_text()))
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is out of date: run OrchKit/Scripts/gen_retry_table.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
