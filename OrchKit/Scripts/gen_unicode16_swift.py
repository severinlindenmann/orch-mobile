#!/usr/bin/env python3
"""Generates Sources/OrchProtocol/Unicode16Data.swift from orch-core's bundled Unicode 16.0 tables.

Usage: gen_unicode16_swift.py <path to orch-core plugins/orch-core/src/orch/canon/_unicode16.py> <orch-core commit sha>
The input is itself generated by orch-core tests/canon/gen_unicode16.py on a Python with unidata_version 16.0.0.
"""
import re, sys
src, sha = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
out = ["// GENERATED by Scripts/gen_unicode16_swift.py. Do not edit.",
       f"// Source: orch-core plugins/orch-core/src/orch/canon/_unicode16.py at commit {sha} (Unicode 16.0.0).",
       "// Format: one record per line, hex fields separated by spaces (decimal for combining classes).",
       "", "enum Unicode16Data {", '    static let version = "16.0.0"']
for name, swift in [("ASSIGNED_RANGES", "assigned"), ("CF_RANGES", "format"), ("CCC_RANGES", "ccc"),
                    ("DECOMP", "decomp"), ("COMPOSABLE", "composable")]:
    m = re.search(name + r' = """\n(.*?)"""', text, re.S)
    body = m.group(1).strip("\n")
    out.append(f'    static let {swift} = """\n{body}\n"""')
out.append("}")
open("Sources/OrchProtocol/Unicode16Data.swift", "w", encoding="utf-8").write("\n".join(out) + "\n")
