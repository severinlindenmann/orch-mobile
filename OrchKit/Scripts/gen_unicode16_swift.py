#!/usr/bin/env python3
"""Generates Sources/OrchProtocol/Unicode16Data.swift from orch-core's bundled Unicode 16.0 tables.

    gen_unicode16_swift.py CORE_UNICODE16_PY CORE_COMMIT_SHA [--check]

CORE_UNICODE16_PY is orch-core plugins/orch-core/src/orch/canon/_unicode16.py (itself generated by orch-core
tests/canon/gen_unicode16.py on a Python with unidata_version 16.0.0). The output path does not depend on the working directory.
--check regenerates in memory and exits 1 if the checked-in file differs: run it in CI against the pinned core checkout when the
tables or the pinned commit change. The file also carries `digest` (SHA-256 of its data blocks), which a unit test recomputes, so
a hand edit of the data is caught without core.

Only the blocks the phone uses are emitted. A core-parity `suspicious()` would also need MARK_RANGES and CF_RANGES: add them to BLOCKS.
"""
import argparse, hashlib, pathlib, re, sys

BLOCKS = [("ASSIGNED_RANGES", "assigned"), ("CCC_RANGES", "ccc"), ("DECOMP", "decomp"), ("COMPOSABLE", "composable")]
OUT = pathlib.Path(__file__).resolve().parent.parent / "Sources" / "OrchProtocol" / "Unicode16Data.swift"


def render(text: str, sha: str) -> str:
    out = ["// GENERATED by Scripts/gen_unicode16_swift.py. Do not edit.",
           f"// Source: orch-core plugins/orch-core/src/orch/canon/_unicode16.py at commit {sha} (Unicode 16.0.0).",
           "// Format: one record per line, hex fields separated by spaces (decimal for combining classes).",
           "", "enum Unicode16Data {", '    static let version = "16.0.0"']
    h = hashlib.sha256()
    for name, swift in BLOCKS:
        m = re.search(name + r' = """\n(.*?)"""', text, re.S)
        body = m.group(1).strip("\n")
        h.update((swift + "\n" + body + "\n").encode())
        out.append(f'    static let {swift} = """\n{body}\n"""')
    out.append(f'    /// SHA-256 over `name + "\\n" + block + "\\n"` for each block in this order: assigned, ccc, decomp, composable.')
    out.append(f'    static let digest = "{h.hexdigest()}"')
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source"); ap.add_argument("sha"); ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    new = render(pathlib.Path(a.source).read_text(encoding="utf-8"), a.sha)
    if a.check:
        if OUT.read_text(encoding="utf-8") != new:
            print("Unicode16Data.swift drifted from the pinned core tables", file=sys.stderr); return 1
        return 0
    OUT.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
